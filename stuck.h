#ifndef __STUCK_H__
#define __STUCK_H__

#include <stdbool.h>

#include "pkgdet.h"

/* Сколько несовпадений переднего плана подряд нужно, чтобы снять удержание.
 * Одно может быть случайным (переключение окон), два — уже уход плеера. */
#define STUCK_CONFIRM	2

typedef enum
{
	/* Ничего не делаем */
	STUCK_NONE = 0,
	/* Проба на старте видео не удалась, пакет был пуст — заполнили его сейчас
	 * (без этого сторож не работал бы вообще) */
	STUCK_FILL_PKG,
	/* Проба переднего плана не удалась: сказать в журнал (один раз на видео),
	 * иначе отказ неотличим от «всё в порядке» */
	STUCK_BLIND,
	/* Плеер ушёл с переднего плана, а счётчик кадров стоит — снять удержание */
	STUCK_GIVE_UP,
} stuck_action_t;

typedef struct
{
	/* Плеер, который вёл текущее видео (проба на его старте) */
	char pkg [PKG_NAME_LEN];
	/* Сколько проверок подряд передний план не совпадает с pkg */
	int mismatch;
	/* Сказали ли уже в журнал про отказ пробы (один раз на видео) */
	bool blind_logged;
} stuck_state_t;

/* Новое видео (или конец старого): пакет и счётчики забыть. */
void stuck_reset (stuck_state_t *st);

/* Запомнить пакет плеера, ведущего видео (проба на старте видео). */
void stuck_set_pkg (stuck_state_t *st, const char *pkg);

/* Что делать на очередной проверке сторожа.
 *
 * @arg st        состояние сторожа
 * @arg probe_rc  код возврата pkg_probe: 0 — проба удалась, иначе отказ
 * @arg top_pkg   передний план (значим только при probe_rc == 0)
 *
 * Состояние обновляется здесь же: STUCK_FILL_PKG записывает пакет,
 * STUCK_BLIND выставляется один раз на видео, счётчик несовпадений растёт
 * и сбрасывается по месту. Вызывающему остаётся выполнить само действие
 * (снятие удержания) — и после него позвать stuck_reset. */
stuck_action_t stuck_step (stuck_state_t *st, int probe_rc, const char *top_pkg);

#endif /* __STUCK_H__ */
