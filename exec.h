#ifndef EXEC_H
#define EXEC_H

#include <stddef.h>

/* Максимальная длина команды (с учётом перенаправления stderr в stdout). */
#define EXEC_CMD_MAX	1024

/* Команда не уложилась в отведённое время (её дерево процессов убито).
 * Отличается от -1: вызывающий может сказать об этом в журнал иначе. */
#define EXEC_TIMEOUT	(-100)

/* Предел времени на команду по умолчанию. Назначение — только антизависание:
 * раньше зависший app_process или dumpsys останавливал цикл демона навсегда.
 * Значение намеренно щедрое: честные команды нового пути (dumpsys
 * SurfaceFlinger/display под нагрузкой, запуск app_process) идут сотни
 * миллисекунд, и убивать их на 3 с нельзя — на ATV14 обнулённая таблица
 * режимов означает «переключать нечем». */
#define EXEC_TIMEOUT_MS_DEFAULT	10000

/* Задать предел времени на команду (мс); значение <= 0 возвращает умолчание.
 * Нужен тестам (tests/test_exec.c проверяет и убийство дерева процессов) и
 * возможной тонкой настройке; демон работает на умолчании. */
void exec_set_timeout_ms (int ms);

/* Выполнить команду через /system/bin/sh и захватить stdout+stderr.
 * Возврат: 0 = команда запущена, -1 = не удалось запустить. */
int exec_capture (const char *cmd, char *out, size_t out_sz);

/* То же, что exec_capture, но отдаёт код возврата команды (0 — успех).
 * Нужно там, где важен именно статус (вендорный помощник: он возвращает
 * ненулевой код, если сервис недоступен или режим отвергнут).
 * Возврат: -1 — команду запустить не удалось; иначе — код возврата команды. */
int exec_status (const char *cmd, char *out, size_t out_sz);

#endif
