#ifndef PAUSE_H
#define PAUSE_H

#include <stdbool.h>

/* «Терпение к паузе»: switch.delay.off на новом пути (Android 10-14).
 *
 * На старом пути ключ откладывает возврат режима после события «видео
 * кончилось» (uevent декодера). На новом пути таких событий нет: демон сам
 * опрашивает счётчик кадров, и остановленное видео с плеером на экране
 * неотличимо от настоящей паузы (живой замер — журнал §32.1). Поэтому здесь
 * ключ означает предел удержания режима на паузе:
 *
 *   delay_ms == 0 — держать режим до конца паузы (как было до этого ключа);
 *   delay_ms > 0  — пауза дольше предела считается концом видео: исходный
 *                   режим возвращается, а удержанный запоминается, чтобы на
 *                   возобновлении вернуться к нему без нового замера.
 *
 * Память о режиме паузы привязана к текущему видео: она сбрасывается, когда
 * видео сменилось (pause_forget), иначе на новом видео демон вернул бы режим
 * прежнего, не измерив частоту.
 */

typedef enum
{
	PAUSE_NONE = 0,	/* ничего не делаем */
	PAUSE_END,	/* пауза пережила предел — считать её концом видео */
	PAUSE_RESUME,	/* счётчик снова растёт — вернуть удержанный режим */
} pause_action_t;

typedef struct
{
	bool armed;	/* удержанный режим паузы запомнен */
	int sf_id;	/* какой режим к нему вернуть (id в таблице SurfaceFlinger) */
} pause_state_t;

/* Один шаг наблюдения за паузой.
 *   paused     — счётчик кадров стоит (два опроса подряд без роста),
 *   held       — режим удержан демоном,
 *   video      — видео активно (по дебаунсу декодера),
 *   cur_sf_id  — текущий применённый режим (-1 — неизвестен),
 *   held_sf_id — режим, который демон удерживает,
 *   stall_us   — сколько счётчик кадров не растёт, микросекунды,
 *   delay_ms   — switch.delay.off, миллисекунды (0 — держать до конца паузы).
 * Состояние между вызовами — в st. */
pause_action_t pause_step (bool paused, bool held, bool video, int cur_sf_id,
                           int held_sf_id, unsigned long long stall_us,
                           int delay_ms, pause_state_t *st);

/* Видео сменилось (новый инстанс декодера, конец видео, сброс счётчика):
 * память о режиме паузы к новому видео не относится. */
void pause_forget (pause_state_t *st);

#endif
