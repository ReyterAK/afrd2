#ifndef SEQ_H
#define SEQ_H

#include <stdbool.h>

/* Последовательность «применили режим → сверили частоту → повторили → сдались»
 * (журнал §124–§128). Вынесена из run_atv14 в чистую функцию: решение зависит
 * только от прочитанной частоты и запомненного состояния, поэтому его можно
 * прогнать на логах тестеров без железа (tests/test_seq.c).
 *
 * Почему отдельно: эта последовательность дважды ломалась на живых боксах, и
 * каждый раз разбор шёл по логу вручную. Правила, которые здесь закреплены:
 *
 *  * формат ставится только когда частота совпала с запрошенной (I3);
 *  * повтор бывает один, дальше — сдача (I1);
 *  * сдача держится до конца видео, её не снимают ни перепроверка, ни
 *    подсказка плеера, ни «режим не найден» (I2);
 *  * остаться на промежуточном режиме можно, только если это действительно
 *    удвоение цели: иначе «оставляю удвоение» — это исходный режим, и его
 *    надо возвращать штатным путём, вместе с цветовым профилем. */

typedef enum
{
	SEQ_IDLE = 0,	/* расхождения ещё не было */
	SEQ_CONFIRM,	/* ждём подтверждения повторным чтением */
	SEQ_RETRIED,	/* повтор уже был, смотрим результат */
} seq_state_t;

typedef enum
{
	SEQ_NOTHING = 0,	/* ничего не делать */
	SEQ_RECHECK,		/* перечитать частоту через 800 мс */
	SEQ_RETRY,		/* применить промежуточный режим, затем целевой */
	SEQ_KEEP_MID,		/* остаться на промежуточном (удвоении), сдаться */
	SEQ_RESTORE,		/* вернуть исходный режим, сдаться */
	SEQ_SET_FORMAT,		/* режим устоялся и частота та — можно писать формат */
} seq_action_t;

typedef struct
{
	seq_state_t state;
	bool gave_up;
} seq_t;

typedef struct
{
	seq_action_t action;
} seq_step_t;

/* Режим устоялся: vhz — фактическая частота (0 — узел не читается),
 * expect_hz — запрошенная (0 — сверять нечего), mid_hz — частота
 * промежуточного режима (0 — промежуточного нет), mid_is_double — это
 * действительно удвоение цели, а не подставленный исходный режим. */
seq_step_t seq_settled (seq_t *st, int vhz, int expect_hz,
                        int mid_hz, bool mid_is_double);

/* Повтор не удался (применение вернуло ошибку): решаем, где остаться.
 * mid_applied — промежуточный режим применился, target_applied — целевой. */
seq_action_t seq_retry_result (seq_t *st, bool mid_applied, bool mid_is_double);

/* Режим применён по решению: следующая сверка начинается с чистого состояния,
 * но сдача (gave_up) не снимается — её снимает только новое видео. */
void seq_note_applied (seq_t *st);

/* Новое видео: всё начинается заново, включая право на повтор. */
void seq_new_video (seq_t *st);

bool seq_gave_up (const seq_t *st);

/* Сдались по этому видео — новые переключения запрещены (I2). Проверяют все
 * пути, которые ставят want_sf_id в обход замера: подсказка плеера, быстрое
 * решение, «режим не найден». */
bool seq_allows_switch (const seq_t *st);

/* Сдаться сейчас, не дожидаясь повтора: режима для нужной частоты нет в
 * таблице — повтор замера его не создаст. */
void seq_give_up (seq_t *st);

#endif
