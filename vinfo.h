#ifndef VINFO_H
#define VINFO_H

/* Фактическая частота дисплея по узлу вендорного драйвера.
 *
 * Зачем: имя режима одно на пару 23.976/24.000 (как и 29.97/30, 59.94/60),
 * а какой именно вариант отдаёт HDMI, решают тайминги — на новом пути их
 * задаёт фреймворк (таблица режимов SurfaceFlinger), на вендорном —
 * frac_rate_policy, который SystemControl переписывает при каждом применении
 * (журнал §72–§73). Чтение sync_duration_num/den из vinfo — независимая
 * проверка «ядро получило то, что просили»: точная дробь, а не имя режима. */
#define VINFO_PATH "/sys/class/display/vinfo"

/* Разбор вывода vinfo: строки "sync_duration_num: 23976" и
 * "sync_duration_den: 1000". Возврат: 1 — оба поля найдены и годны,
 * 0 — нет (узел другого формата или ден == 0). */
int vinfo_parse_sync (const char *dump, int *num, int *den);

/* Частота из пары num/den в 24.8 fixed-point (23976/1000 -> 6138).
 * Возврат: 0 при некорректных значениях. */
int vinfo_hz (int num, int den);

/* Прочитать узел и вернуть фактическую частоту (24.8). num/den (если не NULL)
 * заполняются сырыми значениями для журнала.
 * Возврат: частота или 0 — узел недоступен/не разобран. */
int vinfo_sync_hz (const char *path, int *num, int *den);

#endif
