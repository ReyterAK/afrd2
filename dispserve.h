#ifndef DISPSERVE_H
#define DISPSERVE_H

/*
 * Постоянный помощник смены режима (Android 10/11, Amlogic).
 *
 * Разовый запуск `app_process` стоит ~490 мс (замер 2026-10-18 на ATV11) —
 * столько же, сколько сам HAL на быстром ТВ. Помощник держит VM и классы HIDL
 * загруженными и принимает имена режимов построчно, поэтому на смену остаётся
 * только работа HAL (замер: тот же режим 20 мс, смена 360-1090 мс вместо
 * 850-1760 мс).
 *
 * Процесс запускается лениво — при первой смене режима — и переиспользуется.
 * Любой отказ (не запустился, не ответил за дедлайн, вернул ошибку) означает
 * возврат к разовому запуску: помощник — ускорение, а не единственный путь.
 */

/* Применить режим через постоянный помощник.
 * Возврат: 0 — режим применён; -1 — помощник недоступен (нужен разовый запуск);
 *          -2 — помощник ответил отказом (режим не применён, повторять разовым
 *               запуском бессмысленно). */
int dispserve_apply (const char *script, const char *mode_name);

/* Завершить помощник (вызывается при выходе демона и при переинициализации). */
void dispserve_stop (void);

#endif
