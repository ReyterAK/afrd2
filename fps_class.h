#ifndef FPS_CLASS_H
#define FPS_CLASS_H

#include <stdbool.h>

#define FPS_RATE_COUNT 8

/* Классификация измеренной частоты в ближайшую стандартную.
 * Возврат: fixed-point 24.8 Гц (напр. 23.976 -> 6138) или 0, если вне допуска. */
int fps_classify (double measured);

/* Группа режимов: частоты, которые на HDMI дают один и тот же режим.
 * 23.976 и 24 (как и 29.97/30, 59.94/60) различаются на 0.1% и выбираются
 * политикой fractional/exact, поэтому при решении «хватит ли разрешения окна»
 * считаются одной частотой. Возврат: 0 — нестандартная частота. */
int fps_rate_group (int hz);

/* Решение по окну замера счётчика кадров декодера.
 * Счётчик дискретен (±1 кадр за окно) и метки времени имеют неопределённость,
 * поэтому решение принимается, только если весь доверительный интервал
 * попадает в одну группу частот (fps_rate_group). Иначе окно надо расширять.
 *   frames_delta — прирост счётчика кадров между крайними выборками;
 *   dt_us        — интервал между выборками (середины чтений), мкс;
 *   dt_unc_us    — неопределённость интервала (±), мкс.
 * Возврат: 1 — решение есть (*hz_out = fixed-point 24.8 Гц); 0 — окно мало. */
int fps_classify_window (unsigned long long frames_delta, unsigned long long dt_us,
                         unsigned long long dt_unc_us, int *hz_out);

/* То же, но с поправкой на систематическое завышение счётчика кадров плеером:
 * frames_delta уменьшается в correct раз (correct = 1 + pct/100, см.
 * fps_correct_factor) вместе с ±1 кадром неопределённости. correct <= 0 или 1.0
 * — без поправки. */
int fps_classify_window_scaled (unsigned long long frames_delta, unsigned long long dt_us,
                                unsigned long long dt_unc_us, double correct, int *hz_out);

/* Решение по окну с поправками: frames_adj = frames_delta / factor - offset * dt_с.
 *   factor — относительная поправка плеера (fps.correct.list), 1.0 — нет;
 *   offset — аддитивная поправка в кадрах/с (fps.correct.av1.offset), 0.0 — нет.
 * Аддитивная нужна отдельно от множителя: завышение AV1-тракта на стенде
 * постоянно в кадрах/с (24.52 вместо 24.00), а не в процентах.
 * Возврат: 1 — решение есть (*hz_out), 0 — окно мало. */
int fps_classify_window_corrected (unsigned long long frames_delta, unsigned long long dt_us,
                                   unsigned long long dt_unc_us,
                                   double factor, double offset, int *hz_out);

/* ---- Поправка на завышение счётчика кодеком (fps.correct.av1.*) ----
 *
 * AV1-тракт декодера S905X5M отдаёт больше кадров, чем номинал: живой замер
 * 2026-10-01 в стороннем плеере (Just Player, один и тот же файл Sintel
 * 24.000 fps): H.264 — 24.002 fps, AV1 — 24.520 fps (+0.52 кадра/с, n=3/2).
 * Штатный клиент YouTube добавляет к этому своё (границы DASH-сегментов).
 *
 * offset_fps <= 0 — поправка выключена. package == NULL или "" — поправка для
 * любого плеера; иначе — только для указанного. */
void fps_correct_set_av1 (double offset_fps, const char *package);

/* Сбросить поправку (используется fps_correct_clear и при enable=0). */
void fps_correct_clear_av1 (void);

/* Поправка, применимая к этому декодеру и плееру (0.0 — не применять). */
double fps_correct_av1_offset (const char *device, const char *package);

/* ---- Относительная поправка AV1 (fps.correct.av1.pct) ----
 *
 * На Android 10/11 завышение AV1-тракта оказалось ПРОПОРЦИОНАЛЬНЫМ: живой замер
 * 2026-10-18 на X4 (AV1, штатный YouTube): 23.976 -> 25.40 (+5.9 %),
 * 59.94 -> 63.30 (+5.6 %). Аддитивная поправка (fps.correct.av1.offset) такое
 * не лечит: на 24 fps нужно −1.4 кадра/с, на 60 fps — −3.4. Относительная
 * поправка одна на все частоты.
 *
 * pct <= 0 — выключена. Применяется только к AV1-декодеру (по имени устройства)
 * и, если задан пакет, только к нему. */
void fps_correct_set_av1_pct (double pct, const char *package);

/* Множитель (1.0 — поправки нет): измеренную частоту надо РАЗДЕЛИТЬ на него. */
double fps_correct_av1_factor (const char *device, const char *package);

/* ---- Одна настройка на поправку AV1 (fps.correct.av1) ----
 *
 * Раньше их было две и они применялись ОДНОВРЕМЕННО: аддитивная
 * (fps.correct.av1.offset, кадр/с) и относительная (fps.correct.av1.pct, %).
 * Обе описывают одно явление — завышение счётчика AV1-трактом, — и включить
 * их вместе значит скорректировать дважды: при pct=5.7 и offset=0.1 контент
 * 25.000 измеряется как 24.90 (см. журнал §99.5). Модель завышения — свойство
 * платформы (на ATV14 оно аддитивное, на ATV11 пропорциональное), а не выбор
 * пользователя, поэтому модель выбирает демон.
 *
 * Ключ fps.correct.av1:
 *   "auto"  — значение платформы (калиброванное; 0 — не калибровано);
 *   "off"/"0" — выключено;
 *   число   — относительная поправка в процентах (только она).
 * Если ключа нет — старое поведение (fps.correct.av1.offset / .pct), но
 * взаимоисключающе: при pct > 0 аддитивная игнорируется (и это видно в логе). */
typedef enum
{
	FPS_AV1_OFF = 0,	/* выключено */
	FPS_AV1_AUTO,		/* значение платформы */
	FPS_AV1_PCT,		/* задано числом, относительная */
	FPS_AV1_LEGACY_ADD,	/* старый ключ .offset */
	FPS_AV1_LEGACY_PCT,	/* старый ключ .pct */
} fps_av1_src_t;

typedef struct
{
	double factor;		/* 1 + pct/100, 1.0 — нет */
	double offset;		/* кадр/с, 0.0 — нет */
	fps_av1_src_t src;
	bool legacy_conflict;	/* оба старых ключа заданы — аддитивная проигнорирована */
} fps_av1_t;

/* Разрешить настройку в пару (factor, offset).
 *   value       — значение fps.correct.av1 или NULL, если ключа нет;
 *   legacy_add  — fps.correct.av1.offset;
 *   legacy_pct  — fps.correct.av1.pct;
 *   auto_add / auto_pct — значения платформы для "auto" (0 — не калибровано). */
void fps_av1_resolve (const char *value, double legacy_add, double legacy_pct,
                      double auto_add, double auto_pct, fps_av1_t *out);

/* ---- Поправка частоты для конкретного плеера (fps.correct.*) ----
 *
 * Разные плееры подают кадры в декодер по-разному: на живом стенде (2026-10-01)
 * приложение YouTube на 24-фпс ролике давало по счётчику ~25.2 fps (+5%), а
 * тот же файл в VLC — ровно 24.0. Граница класса 24 -> 25 лежит на 24.49, поэтому
 * +5% уводит 24-фпс контент в 25 Гц. Поправка задаётся пользователем на плеер
 * (пакет) и применяется к замеру до классификации; по умолчанию список пуст, то
 * есть поведение прежнее.
 *
 * Строка списка: "<пакет>=<проценты>" через пробел, например
 * "com.google.android.youtube.tv=4.5". Положительное значение — плеер завышает
 * частоту. Некорректные записи игнорируются. */
#define FPS_CORRECT_MAX 8

void fps_correct_load (const char *list);
void fps_correct_clear (void);

/* Множитель для пакета (1.0 — поправки нет). package == NULL — тоже 1.0. */
double fps_correct_factor (const char *package);

/* Уточнение решения заявленной частотой кадра (vdec_status: `frame dur`).
 *
 * На живых IPTV-потоках замер по счётчику кадров систематически завышен: плеер
 * повторно декодирует кадры на границах HLS-сегментов (измерено 2026-09-30:
 * поток 23.976 fps — по PTS сегмента — счётчик показывал 24.56 fps, +2.4%), и
 * 24-фпс контент уходил в 25 Гц. Заявленная частота в этом случае совпадает с
 * номиналом, поэтому берём её — но только когда она близка к измеренной
 * (не дальше max_pct): далёкое значение означает мусор в поле (на синтетических
 * клипах драйвер рапортует 30 fps при реальных 23.976) и игнорируется.
 *
 * measured_hz — решение fps_classify_window() (fixed-point 24.8);
 * declared_fps — 96000/frame dur из vdec_status;
 * max_pct — допуск расхождения, % (0 — уточнение выключено).
 * Возврат: 1 — решение уточнено (*hz_out = дробный представитель группы
 * заявленной частоты), 0 — заявленная частота не годится. */
int fps_refine_declared (int measured_hz, double declared_fps, double max_pct, int *hz_out);

/* Вердикт по окну подачи видео-слоя (dumpsys SurfaceFlinger --latency).
 *
 * median_ms  — медиана интервалов между фактическими метками кадров;
 * period_ms  — период обновления дисплея из того же дампа;
 * expect_ms  — ожидаемый интервал контента (1000/ожидаемая частота);
 * gap_pct    — доля интервалов длиннее 1.5 базы (порог выброса);
 * gap_thr    — fps.feed.gap.pct, %.
 *
 * База — максимум из expect_ms и period_ms. Возврат:
 *   FPS_CADENCE_OK     — подача в норме (или быстрее базы — поля);
 *   FPS_CADENCE_UNEVEN — медиана в норме, но доля выбросов выше порога:
 *                        плеер теряет кадры, смена режима не помогает;
 *   FPS_CADENCE_HALVED — медиана вдвое больше базы: дефект vsync-пути,
 *                        лечится сменой режима «туда-обратно».
 *
 * UNEVEN и HALVED различаются порогом 1.5×: раньше оба случая давали
 * «вдвое реже» и оба лечились переключением, из-за чего подача с потерями
 * кадров получала лишние мигания 24 -> 60 -> 24 (журнал §150). */
#define FPS_CADENCE_OK		0
#define FPS_CADENCE_UNEVEN	1
#define FPS_CADENCE_HALVED	2

int fps_cadence_verdict (int median_ms, int period_ms, int expect_ms,
                         int gap_pct, int gap_thr);

/* Частота контента по средней подаче видео-слоя (журнал §179).
 *
 * Метки `actualPresentTime` в буфере SurfaceFlinger не зависят от счётчика
 * кадров декодера, а именно он на AV1-тракте YouTube завышен на ~5 % (24 к/с
 * читается как 25.2), из-за чего 24 уходило в 25 Гц. Подача это различает:
 * 24 к/с на 60 Гц дают 3:2 (среднее 41.7 мс), 25 к/с — 2,2,3 (40.0 мс).
 *
 * frames — число валидных меток; avg_ms — средний интервал; period_ms —
 * период дисплея; gap_pct — доля интервалов-выбросов (пауза, переход).
 * Возврат: 1 и класс частоты (24.8) или 0, если данных мало, слой обновляется
 * на частоте дисплея (о контенте ничего не говорит) или в буфере есть выброс. */
int fps_layer_rate_hz (int frames, double avg_ms, double period_ms,
                       int gap_pct, int *hz_out);

/* Признак ПЕРЕХОДА контента по двум половинам буфера подачи слоя (журнал §181).
 *
 * Реклама в начале ролика и смена канала — две каденции в одном окне: половина
 * буфера ещё от прежнего потока, половина уже от нового. Средние и медианы по
 * всему буферу описывают смесь, проба слоя отвергается (gap), и решение
 * принимается по загрязнённому окну (живой случай: 46 % интервалов вне ±20 %).
 *
 *   a_ms, b_ms      — медианные интервалы первой и второй половины, мс;
 *   na, nb          — сколько интервалов в каждой половине;
 *   span_ms         — сколько времени покрывает весь буфер;
 *   since_switch_ms — сколько прошло с нашей смены режима (-1 — не было).
 *
 * Возврат 1 — классы частот половин разные и наша смена режима в буфер не
 * попадает; 0 — перехода нет, данных мало или половины разные из-за нашей же
 * смены режима (период прежнего и нового режима при том же контенте).
 *
 * Порог 40 интервалов на половину: при 24 к/с это 1.7 с, при 60 к/с — 0.7 с;
 * меньшие половины слишком шумные для сравнения классов. */
int fps_layer_transition (double a_ms, double b_ms, int na, int nb,
                          double span_ms, double since_switch_ms);

/* Точный (целочисленный) представитель группы — для `mode.use.fract=2`:
 * 23.976 -> 24.000, 29.97 -> 30.000, 59.94 -> 60.000 (25 и 50 без изменений).
 * Нужен, когда ТВ/прошивка предпочитает точные режимы; если такого режима в
 * таблице нет, resolver всё равно подберёт ближайший (см. sfmodes_find).
 * Возврат: fixed-point 24.8 Гц или 0, если частота не из таблицы. */
int fps_rate_exact_member (int hz);

/* Дробный представитель группы — для `mode.use.fract=1` («всегда дробная»):
 * 24.000 -> 23.976, 30.000 -> 29.97, 60.000 -> 59.94 (25 и 50 без изменений).
 * Нужен источникам, которые называют частоту точно (подсказка плеера 24000,
 * быстрый путь по полю `frame rate`): без него первый переход делался в целый
 * режим, а замер через 14–20 с переключал его в дробный — два мигания на одном
 * видео (живой случай `.50`, канал 210, 04.11).
 * Возврат: fixed-point 24.8 Гц или 0, если частота не из таблицы. */
int fps_rate_fract_member (int hz);

/* Точный (целочисленный) член группы, если источник ЗАЯВИЛ именно его —
 * для `mode.use.fract=0` («Авто»).
 *
 * Заявить целое могут только точные источники: подсказка плеера
 * (frame_rate_hint, 24.8 fixed-point: 24000 -> 6144 против 23976 -> 6138)
 * и `frame dur` из vdec_status (96000/4000 = 24.000 против 96000/4004 =
 * 23.976). Грубое поле `frame rate` (целые fps) доказательством не является:
 * оно целое всегда и пару 23.976/24 не различает, поэтому сюда не передаётся.
 *
 * declared_hz — заявленная частота, 24.8 fixed-point.
 * Возврат: 6144/7680/15360 (24.000/30.000/60.000) или 25/50 без изменений;
 *          0 — заявлено дробное, значение вне таблицы или далеко от неё. */
int fps_rate_declared_exact (int declared_hz);

/* Политика `mode.use.fract` для нового пути (Android 10-14).
 *   hz         — частота, которую надо привести к режиму, 24.8 fixed-point
 *                (решение замера — обычно уже дробный представитель группы,
 *                подсказка плеера и быстрое решение — любая из пары);
 *   declared_hz — заявленная частота, 24.8 fixed-point (0 — источника нет);
 *   policy     — значение ключа: 0 «Авто», 1 «дробные», 2 «целые».
 * Возврат: частота режима. 1 — дробный представитель группы (24.000 -> 23.976),
 * 2 — целый (23.976 -> 24.000), 0 — целый, только если источник заявил целое
 * и оно в той же группе, что замер. Любое иное значение не меняет решение.
 *
 * Применять надо ко всем источникам частоты, а не только к замеру: подсказка
 * плеера (24000) и поле `frame rate` быстрого пути дают 24.000, и при
 * «предпочитать дробные» без этой функции первый переход уходил в целый режим,
 * а замер через 14–20 с — в дробный (два мигания, живой случай 04.11). */
int fps_rate_apply_policy (int hz, int declared_hz, int policy);

/* Расхождение двух независимых оценок частоты — для сверки «счётчик кадров
 * против подачи видео-слоя» (журнал §87.4).
 * Возврат: 0 — оценки сошлись (отношение меньше 1.6) или одна из них нулевая;
 *          иначе отношение большей к меньшей в процентах (ровно вдвое — 200). */
int fps_sources_ratio_pct (int a_hz, int b_hz);

/* Класс частоты по ЗАЯВЛЕННОЙ драйвером частоте кадра (целые fps: 24, 25, 30).
 * Возврат: fixed-point 24.8 Гц или 0, если значение нестандартное/мусор.
 *
 * Нужен быстрому пути решения (fps.declare.fast): штатный системный AFR Amlogic
 * берёт именно заявленную частоту из vdec_status и потому переключает за 2-4 с
 * (журнал §33.19). Мы делаем так же, но помечаем решение предварительным —
 * замер продолжает работать и правит режим при расхождении. */
int fps_declared_class (int declared_fps);

/* Разные ли группы у двух частот (fps_rate_group): 23.976 и 24 — одна группа,
 * 24 и 30 — разные. Слева ноль означает «сравнивать нечего» -> false. */
bool fps_group_differs (int a_hz, int b_hz);

int fps_rate_hz (int index);
const char *fps_rate_name (int index);
int fps_rate_index_for_hz (int hz);

/* fb-декодер Amlogic (amvdec_*_fb_) считает кадры вдвое (журнал §90): живой
 * бокс X96 X10 Pro, `amvdec_h265_fb_`, узел заявляет 24 к/с, а огибающая
 * видит ~48 и уводит режим в 50. Если измеренная частота попала в окно
 * 1.5..2.5 заявленной, возвращается заявленная; вне окна — измеренная. */
int fps_fb_declared_hz (int measured_hz, int declared_hz);

#endif
