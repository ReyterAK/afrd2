#ifndef CEILING_H
#define CEILING_H

#include <stddef.h>

/*
 * Сброс «потолка» частоты у плеера (Android 12-14, журнал §47.9).
 *
 * Плеер (штатный YouTube TV на Cobalt) запоминает частоту дисплея в начале
 * сессии проигрывания и планирует кадры по min (потолок, текущий режим);
 * внешняя смена режима потолок не поднимает. Потолок перечитывается при смене
 * конфигурации экрана — самое дешёвое из таких событий — изменение плотности
 * на единицу с немедленным возвратом (замер на ATV14: провал подачи ~80 мс).
 *
 * Модуль держит только разбор и сборку команд: их выполняет afrd.c, чтобы
 * host-тесты не зависели от shell.
 */

/* Плотность, которую выставляем на время сброса: действующая + 1. */
#define CEILING_DENSITY_STEP	1

/* Разбор вывода `wm density`:
 *     Physical density: 320
 *     Override density: 321          (строки может не быть)
 * Возврат: 0 — разобрано; *cur — действующая плотность, *had_override —
 * задана ли плотность пользователем (её надо вернуть, а не сбрасывать),
 * *next — плотность для первого шага (cur + CEILING_DENSITY_STEP).
 * -1 — вывод не разобран (тогда сброс не выполняется). */
int ceiling_density_parse (const char *wm_out, int *cur, int *had_override, int *next);

/* Команда возврата плотности: прежнее значение override либо `wm density reset`.
 * Возврат: 0 — ок, -1 — не влезло в буфер. */
int ceiling_build_restore (char *buf, size_t n, int had_override, int prev);

/* Нужно ли сбрасывать потолок: цель выше уже подтверждённого (частоты в
 * 1/256 Гц). Допуск CEILING_HZ_TOLERANCE — цель гуляет между 59.94 и 60.00,
 * и без него сброс повторялся на каждом уточнении (живая находка 2026-10-18:
 * четыре сброса подряд на ATV11). confirmed_hz <= 0 — потолок неизвестен,
 * сбрасывать нужно. */
#define CEILING_HZ_TOLERANCE	128	/* 0.5 Гц в 1/256 */

int ceiling_should_reset (int confirmed_hz, int target_hz);

/* Второй способ сброса потолка — перезапуск процесса кодека (журнал §60).
 * Он пересоздаёт сессию декодера у плеера, плеер перечитывает режим и подача
 * выправляется с текущей позиции ролика. Замер на ATV14: декодер пропадает на
 * 68 мс и возвращается на 1.1 с (смена плотности — 6.8 с), поэтому этот способ
 * годится и для Android 10/11, где плотность стоила 1.5-2.5 с.
 *
 * Имя сервиса зависит от прошивки, поэтому оно опрашивается. */

/* Команда опроса: печатает «<имя>=<состояние init>» по каждому кандидату.
 * Возврат: 0 — ок, -1 — не влезло в буфер. */
int ceiling_codec_probe_cmd (char *buf, size_t n);

/* Выбрать из вывода опроса имя ЗАПУЩЕННОГО сервиса кодека (приоритет —
 * порядок кандидатов в ceiling.c, не порядок строк). NULL — не найден. */
const char *ceiling_codec_pick (const char *probe_out);

/* Команда перезапуска сервиса с проверкой, что pid сменился (init молча
 * игнорирует ctl.restart для несуществующего сервиса).
 * Возврат: 0 — ок, -1 — не влезло в буфер. */
int ceiling_build_codec_restart (char *buf, size_t n, const char *svc);

#endif
