#include <assert.h>
#include <stdio.h>

#include "../mstime.h"

/* Скачок системных часов отделяем от долгой итерации цикла: настенная дельта
 * сравнивается с монотонной (P3 прохода 2). */
int main (void)
{
	/* итерация шла ровно столько, сколько прошло по часам */
	assert (mstime_jump (5000, 5000) == 0);
	assert (mstime_jump (20000, 20010) == -10);

	/* NTP/ручная правка вперёд: часы ушли на минуту */
	assert (mstime_jump (65000, 5000) == 60000);

	/* правка назад */
	assert (mstime_jump (-30000, 5000) == -35000);

	/* монотонное время доступно и не ноль */
	assert (mstime_mono () > 0);

	printf ("mstime: OK\n");
	return 0;
}
